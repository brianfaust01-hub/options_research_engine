from dataclasses import asdict
from datetime import datetime
from pathlib import Path

import pandas as pd
import yfinance as yf

from config import VERSION, CONFIG_VERSION
from snapshot_writer import write_snapshot


JOURNAL_PATH = Path("data/trade_journal.csv")


def _classify_trade_status(trade_dict: dict):

    if trade_dict.get("action") == "Watch":
        return "WATCHLIST"

    if trade_dict.get("action") != "Evaluate Options":
        return "PASS"

    if trade_dict.get("option_strategy") is None:
        return "NOT_EXECUTABLE"

    if trade_dict.get("contracts") in [None, 0]:
        return "NOT_EXECUTABLE"

    return "PAPER_TRADE_CANDIDATE"


def _get_latest_underlying_price(ticker: str):

    try:

        stock = yf.Ticker(ticker)

        history = stock.history(period="5d")

        if history.empty:
            return None

        return float(history["Close"].iloc[-1])

    except Exception:
        return None


def log_trade_recommendation(trade):

    JOURNAL_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    timestamp = datetime.now()

    trade_dict = asdict(trade)

    trade_dict["RecommendationDate"] = timestamp.isoformat(
        timespec="seconds"
    )

    trade_dict["ProjectVersion"] = VERSION
    trade_dict["ConfigVersion"] = CONFIG_VERSION

    trade_dict["TradeStatus"] = _classify_trade_status(
        trade_dict
    )

    #
    # Research-time market context only.
    #

    trade_dict["EntryUnderlyingPrice"] = (
        _get_latest_underlying_price(
            trade_dict["ticker"]
        )
    )

    #
    # Immutable recommendation snapshot.
    #

    snapshot_info = write_snapshot(
        trade=trade,
        research_row=trade_dict,
    )

    trade_dict["RecommendationID"] = (
        snapshot_info["recommendation_id"]
    )

    trade_dict["SnapshotPath"] = (
        snapshot_info["file_path"]
    )

    trade_dict["SnapshotSchemaVersion"] = (
        snapshot_info["schema_version"]
    )

    #
    # Append to immutable journal.
    #

    df = pd.DataFrame([trade_dict])

    if JOURNAL_PATH.exists():

        existing = pd.read_csv(
            JOURNAL_PATH
        )

        df = pd.concat(
            [
                existing,
                df,
            ],
            ignore_index=True,
        )

    df.to_csv(
        JOURNAL_PATH,
        index=False,
    )